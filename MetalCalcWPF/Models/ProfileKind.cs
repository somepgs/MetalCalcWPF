namespace MetalCalcWPF.Models
{
    /// <summary>
    /// Тип сортамента (форма проката).
    /// Значения прописаны явно, чтобы при добавлении новых позиций
    /// не менялись числа в уже сохранённых записях БД.
    /// </summary>
    public enum ProfileKind
    {
        /// <summary>Лист горячекатаный. ГОСТ 19903-2015.</summary>
        Sheet = 1,

        /// <summary>Уголок равнополочный. ГОСТ 8509-93.</summary>
        AngleEqual = 2,

        /// <summary>Уголок неравнополочный. ГОСТ 8510-86.</summary>
        AngleUnequal = 3,

        /// <summary>Профиль стальной гнутый замкнутый сварной квадратного сечения. ГОСТ 30245-2003.</summary>
        SquareTube = 4,

        /// <summary>Профиль стальной гнутый замкнутый сварной прямоугольного сечения. ГОСТ 30245-2003.</summary>
        RectTube = 5,

        /// <summary>Швеллер горячекатаный. ГОСТ 8240-97.</summary>
        Channel = 6,

        /// <summary>Двутавр горячекатаный. ГОСТ 8239-89 / СТО АСЧМ 20-93.</summary>
        IBeam = 7,
    }

    /// <summary>
    /// Станки, на которых можно выполнить отрезку проката.
    /// Это флаги — один профиль может подходить для нескольких станков.
    /// </summary>
    [System.Flags]
    public enum CuttingMachines
    {
        None = 0,
        Laser = 1 << 0,              // Лазер Bodor (только лист и тонкостенные)
        BandSaw = 1 << 1,            // Ленточная пила (почти всё, кроме очень тонкого листа)
        PressShears = 1 << 2,        // Пресс-ножницы (только уголки)
        Guillotine = 1 << 3,         // Гильотина (только лист, до 8 мм)
        AngleGrinder = 1 << 4,       // Болгарка (ручная резка, что угодно)
    }
}
