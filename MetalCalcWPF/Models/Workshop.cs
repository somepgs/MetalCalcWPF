namespace MetalCalcWPF.Models
{
    /// <summary>
    /// Кто заказал работу: внутренний цех предприятия или внешний клиент.
    /// Хранится как int — стабильные номера, не зависят от перестановки членов.
    /// </summary>
    public enum WorkshopKind
    {
        /// <summary>Цех нашего предприятия (СВ, СК, ХЭСС, сэндвич-панели, металлообработка).</summary>
        Internal = 0,

        /// <summary>Внешний клиент — сторонняя организация или частное лицо.</summary>
        ExternalClient = 1,
    }

    /// <summary>
    /// Справочник цехов и внешних клиентов — заказчиков работы цеха металлообработки.
    ///
    /// <para>На момент внедрения предприятие имеет 5 внутренних цехов:
    /// СВ, СК (столбы ЖБИ), ХЭСС (брусчатка/бордюры), сэндвич-панели,
    /// металлообработка (сами себе тоже могут заказывать ремонт). Они засеваются
    /// миграцией V005. Внешние клиенты добавляются пользователем по мере появления.</para>
    ///
    /// <para>Сущность намеренно простая (без иерархии «Заказчик → Подразделения»),
    /// потому что у нас 5 цехов и горстка клиентов — иерархия будет over-engineering.</para>
    /// </summary>
    public class Workshop
    {
        public int Id { get; set; }

        /// <summary>Отображаемое имя: «Цех СВ», «Цех ХЭСС (брусчатка и бордюры)», «ООО Ромашка».</summary>
        public string Name { get; set; } = string.Empty;

        /// <summary>Внутренний цех или внешний клиент. Влияет только на отображение/фильтры.</summary>
        public WorkshopKind Kind { get; set; } = WorkshopKind.Internal;

        /// <summary>Активен ли — отображается ли в выпадающих списках при создании заказа.</summary>
        public bool IsActive { get; set; } = true;

        /// <summary>Свободная заметка: контактное лицо, договор, особенности и т.п.</summary>
        public string Notes { get; set; } = string.Empty;
    }
}
