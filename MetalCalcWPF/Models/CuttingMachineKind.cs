namespace MetalCalcWPF.Models
{
    /// <summary>
    /// Тип станка резки. Значения синхронизированы с набором булевых флагов
    /// «Совместим с …» у <see cref="RolledProfile"/> (CanLaser, CanBandSaw и т.д.),
    /// чтобы сортамент мог однозначно указывать, на каких станках он режется.
    ///
    /// При добавлении нового значения:
    /// 1) добавь его в конец перечисления (не меняй номера имеющихся — это ключ в БД);
    /// 2) прикрути соответствующий флаг в <see cref="RolledProfile"/>, если станок
    ///    применим к прокату;
    /// 3) обнови редактор станков и расчёт при необходимости.
    /// </summary>
    public enum CuttingMachineKind
    {
        /// <summary>Лазерный станок (основной «чистовой» рез).</summary>
        Laser = 0,

        /// <summary>Ленточнопильный станок.</summary>
        BandSaw = 1,

        /// <summary>Пресс-ножницы.</summary>
        PressShears = 2,

        /// <summary>Гильотина.</summary>
        Guillotine = 3,

        /// <summary>Угловая шлифмашина (болгарка) — ручной рез.</summary>
        AngleGrinder = 4,
    }
}
