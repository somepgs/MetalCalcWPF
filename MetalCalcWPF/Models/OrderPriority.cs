namespace MetalCalcWPF.Models
{
    /// <summary>
    /// Срочность заказа — определяет порядок в очереди цеха металлообработки.
    ///
    /// <para>Хранится как int (стабильные номера). В БД заказы сортируются по
    /// <c>Priority desc, CreatedDate asc</c> — самое срочное сверху, при равной
    /// срочности раньше пришедшая заявка обрабатывается первой.</para>
    /// </summary>
    public enum OrderPriority
    {
        /// <summary>Низкая. Можно сделать «когда руки дойдут» — побочные задачи.</summary>
        Low = 0,

        /// <summary>Обычная. Стандартный поток заявок без особых пометок.</summary>
        Normal = 1,

        /// <summary>Высокая. Передвинуть на ближайшие свободные часы.</summary>
        High = 2,

        /// <summary>Срочно. Дропнуть текущую задачу, делать сейчас.</summary>
        Urgent = 3,
    }
}
